export function applyPlainLanguageEditorial(cases: V3Case[]) {
  cases.forEach((item) => Object.assign(item, caseCopy[item.id]));

  (Object.keys(experienceCopy) as V3CaseId[]).forEach((id) => {
    Object.assign(v4CaseExperience[id], experienceCopy[id]);
  });

  (Object.keys(instructorCopy) as V3CaseId[]).forEach((id) => {
    Object.assign(v4InstructorGuides[id], instructorCopy[id]);
  });

  v4PlaybookModel.more = '답을 주기 전에 먼저 후배의 생각을 듣고, 혼자 결정할 범위와 다시 상의할 조건을 분명히 한다.';
  v4PlaybookModel.less = '급하다는 이유로 내가 대신 결정하거나, 맡긴 뒤 모든 과정을 다시 확인하는 행동을 줄인다.';
  v4PlaybookModel.nextTwoWeeks = '다음 주 실제 업무를 맡길 때 “혼자 결정할 일 / 꼭 알려야 할 일”을 먼저 합의하고, 중간 확인은 한 번만 한다.';
}
